(* Timing proof for a branchless-update binary search compiled for NEORV32.

   Because the left/right pointer updates in the loop body are branchless
   (inline sltu/neg/and/andn/or), every iteration that does not find the key
   costs the same [body_time].  Execution time is therefore exactly

       setup_time + k * body_time + (found_exit_time | notfound_exit_time)

   where k is the number of non-matching iterations.  The proof bounds k
   logarithmically in the array length by tracking the size sz of the
   remaining search interval [left, right]:

     - moving left  = mid+1 shrinks sz to sz/2,      and N.size sz drops by exactly 1
     - moving right = mid-1 shrinks sz to (sz-1)/2,  and N.log2 (sz+1) drops by exactly 1

   giving  0 <= k < N.size len               when the key is found, and
           N.log2 (len+1) <= k <= N.size len  when it is not.

   Each extreme is attained (key at the first midpoint; key below all elements;
   key above all elements of a sorted array), so the derived bounds are tight.
   The timing theorem itself holds for arbitrary array contents: it does not
   assume the array is sorted.

   NOTE: the binary uses the Zbb instruction andn, which requires R5_Andn
   support in Picinae_riscv.v and its timing in RISCVTiming.v. *)


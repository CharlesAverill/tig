(* TIG: generic closing tactics for loop proofs *)
Local Ltac tig_bc :=
  unfold slt, sle in *;
  repeat match goal with
  | H: Z.ltb _ _ = true |- _ => apply Z.ltb_lt in H
  | H: Z.ltb _ _ = false |- _ => apply Z.ltb_ge in H
  | H: Z.leb _ _ = true |- _ => apply Z.leb_le in H
  | H: Z.leb _ _ = false |- _ => apply Z.leb_gt in H
  | H: Z.geb _ _ = true |- _ => apply Z.geb_le in H
  | H: Z.geb _ _ = false |- _ => rewrite Z.geb_leb in H; apply Z.leb_gt in H
  | H: Z.gtb _ _ = true |- _ => apply Z.gtb_lt in H
  | H: Z.gtb _ _ = false |- _ => rewrite Z.gtb_ltb in H; apply Z.ltb_ge in H
  | H: (_ =? _) = true |- _ => apply N.eqb_eq in H
  | H: (_ =? _) = false |- _ => apply N.eqb_neq in H
  | H: (_ <? _) = true |- _ => apply N.ltb_lt in H
  | H: (_ <? _) = false |- _ => apply N.ltb_ge in H
  | H: (_ <=? _) = true |- _ => apply N.leb_le in H
  | H: (_ <=? _) = false |- _ => apply N.leb_gt in H
  | H: negb _ = true |- _ => apply Bool.negb_true_iff in H
  | H: negb _ = false |- _ => apply Bool.negb_false_iff in H
  end.
Local Ltac tig_split_if c :=
  lazymatch c with true => fail | false => fail
  | negb ?c' => destruct c' eqn:? | _ => destruct c eqn:? end.
Local Ltac tig_ifs :=
  repeat (cbn [negb] in *; match goal with
    | |- context[if ?c then _ else _] => tig_split_if c
    | H: context[if ?c then _ else _] |- _ => tig_split_if c
    end); cbn [negb] in *.
(* modular arithmetic: eliminate mod/div into linear constraints *)
Local Ltac tig_pow :=
  repeat match goal with
  | |- context[2 ^ ?n] => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v
  | H: context[2 ^ ?n] |- _ => let v := eval vm_compute in (2 ^ n) in change (2 ^ n) with v in H
  end.
Local Ltac tig_arith :=
  tig_bc; unfold msub in *;
  rewrite ?N.shiftl_mul_pow2, ?N.shiftr_div_pow2 in *; tig_pow;
  zify; Z.div_mod_to_equations; Z.quot_rem_to_equations; lia.
Local Ltac tig_leaf w :=
  first [ assumption | reflexivity
        | (try lazymatch goal with H: w <= ?n |- _ =>
             replace w with n in * by tig_arith end);
          hammer; tig_ifs; solve [ lia | tig_arith ] ].
(* choose disjuncts and iteration witnesses (w, the current iteration, or w+1) *)
Local Ltac tig_try w :=
  lazymatch goal with
  | |- _ \/ _ => first [ left; tig_try w | right; tig_try w ]
  | |- exists _, _ => first [ exists w; tig_try w | exists (w + 1); tig_try w ]
  | |- _ /\ _ => split; [ tig_try w | tig_try w ]
  | |- _ => solve [ tig_leaf w ]
  end.

Definition binary_search_timing_invs (a0 a2 : N)
    (t:trace) : option Prop :=
match t with (Addr a, s) :: t' => match a with
| 0x1e4 => Some (s R_A0 = a0 /\ s R_A2 = a2 /\ a0 < 2^32 /\ a2 < 2^32 /\ cycle_count_of_trace t' = 0)
| 0x1f0 => Some (exists i, s R_A2 = a2 /\
        s R_A3 = a0 /\
        a0 < 2^32 /\
        a2 < 2^32 /\
        cycle_count_of_trace t' = taddi + taddi + taddi + i * (ttbge + tsub + tsrai 1 + tadd + tslli 2 + tadd + tlw + taddi + tfbeq + tsltu + tsltu + taddi + tsub + tand + tandn + tor + taddi + tsub + tand + tandn + tor + tjal))
| 0x1f8 => Some (
        (exists j, cycle_count_of_trace t = taddi + taddi + taddi + j * (ttbge + tsub + tsrai 1 + tadd + tslli 2 + tadd + tlw + taddi + tfbeq + tsltu + tsltu + taddi + tsub + tand + tandn + tor + taddi + tsub + tand + tandn + tor + tjal) + ttbge + tsub + tsrai 1 + tadd + tslli 2 + tadd + tlw + taddi + ttbeq + tjalr) \/
        (exists j, cycle_count_of_trace t = taddi + taddi + taddi + j * (ttbge + tsub + tsrai 1 + tadd + tslli 2 + tadd + tlw + taddi + tfbeq + tsltu + tsltu + taddi + tsub + tand + tandn + tor + taddi + tsub + tand + tandn + tor + tjal) + tfbge + taddi + tjalr))
| _ => None end | _ => None end.

Theorem binary_search_timing:
  forall s t s' x' a0 a2
         (ENTRY: startof t (x',s') = (Addr entry_addr, s))
         (MDL: models rvtypctx s)
         (A0: s R_A0 = a0)
         (A2: s R_A2 = a2),
  satisfies_all
    lifted_prog
    (binary_search_timing_invs a0 a2)
    exits
  ((x',s')::t).
Proof using.
    intros.
    pose proof (models_var R_A0 MDL) as B_A0; simpl in B_A0; rewrite A0 in B_A0.
    pose proof (models_var R_A2 MDL) as B_A2; simpl in B_A2; rewrite A2 in B_A2.
    apply prove_invs.
    Local Ltac step := tstep r5_step.

    simpl. rewrite ENTRY. unfold entry_addr. step. tig_try 0.

    intros.
    eapply startof_prefix in ENTRY; try eassumption.
    eapply preservation_exec_prog in MDL;
        try eassumption; [idtac|apply lift_riscv_welltyped].
    clear - ENTRY PRE MDL. rename t1 into t. rename s1 into s'.

    destruct_inv 32 PRE.

    (* 0x1e4: entry -> loop header *)
    { destruct PRE as (A0 & A2 & B_A0 & B_A2 & Cycles).
      repeat step. all: tig_try 0. }

    (* 0x1f0: loop header -> loop header / exit *)
    { destruct PRE as (i & L0 & L1 & B_A0 & B_A2 & Cycles).
      repeat step. all: tig_try i. }
Qed.

End TimingProof.

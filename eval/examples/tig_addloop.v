        t0 < 2^32 /\
        cycle_count_of_trace t' = tori + tandi + i * (tfbeq + taddi + tsub + ttbeq))
| 0x20 => Some (
        cycle_count_of_trace t' = tori + tandi + t0 * (tfbeq + taddi + tsub + ttbeq) + ttbeq)
| _ => None end | _ => None end.

Theorem addloop_timing:
  forall s t s' x' t0
         (ENTRY: startof t (x',s') = (Addr entry_addr, s))
         (MDL: models rvtypctx s)
         (T0: s R_T0 = t0),
  satisfies_all
    lifted_prog
    (addloop_timing_invs t0)
    exits
  ((x',s')::t).
Proof using.
    intros.
    pose proof (models_var R_T0 MDL) as B_T0; simpl in B_T0; rewrite T0 in B_T0.
    apply prove_invs.
    Local Ltac step := tstep r5_step.

    simpl. rewrite ENTRY. unfold entry_addr. step. tig_try 0.

    intros.
    eapply startof_prefix in ENTRY; try eassumption.
    eapply preservation_exec_prog in MDL;
        try eassumption; [idtac|apply lift_riscv_welltyped].
    clear - ENTRY PRE MDL. rename t1 into t. rename s1 into s'.

    destruct_inv 32 PRE.

    (* 0x8: entry -> loop header *)
    { destruct PRE as (T0 & B_T0 & Cycles).
      repeat step. all: tig_try 0. }

    (* 0x10: loop header -> loop header / exit *)
    { destruct PRE as (i & L0 & L1 & L2 & L3 & B_T0 & Cycles).
      repeat step. all: tig_try i. }
Qed.


Definition addloop_timing_invs (t0 : N)
    (t:trace) : option Prop :=
match t with (Addr a, s) :: t' => match a with
| 0x8 => Some (s R_T0 = t0 /\ t0 < 2^32 /\ cycle_count_of_trace t' = 0)
| 0x10 => Some (exists i, i <= t0 /\
        s R_T0 = t0 ⊕ 4294967295 * i /\
        s R_T2 = 1 /\
